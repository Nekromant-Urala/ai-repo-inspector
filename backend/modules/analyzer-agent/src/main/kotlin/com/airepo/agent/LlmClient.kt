package com.airepo.agent

/**
 * Абстракция над чат-моделью. Позволяет подменять провайдера
 * (сейчас — локальный Ollama) и легко подключать тестовую заглушку.
 */
interface LlmClient {

    /**
     * Выполняет чат-запрос с системным и пользовательским сообщениями
     * и возвращает текст ответа модели.
     */
    fun chat(system: String, user: String): String
}