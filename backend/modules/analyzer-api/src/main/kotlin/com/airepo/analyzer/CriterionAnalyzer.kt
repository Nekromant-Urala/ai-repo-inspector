package com.airepo.analyzer

import com.airepo.domain.CriterionResult

/**
 * Контракт отдельного критерия аудита.
 *
 * Каждый критерий (README, качество кода, тесты, структура, git-история,
 * вклад участников, безопасность) реализуется отдельным модулем, который
 * предоставляет одну (или несколько) реализаций этого интерфейса.
 *
 * Spring находит все реализации и прогоняет их в едином пайплайне.
 */
interface CriterionAnalyzer {

    /** Уникальный идентификатор критерия, например `readme`. */
    val id: String

    /** Человекочитаемое имя для отчёта. */
    val name: String

    /** Выполняет анализ проекта и возвращает результат по критерию. */
    fun analyze(context: AnalysisContext): CriterionResult
}