package com.airepo.domain

/**
 * Жизненный цикл задачи проверки репозитория.
 *
 * Фронтенд опирается на это поле, чтобы показать страницу ожидания
 * (PENDING/RUNNING) до тех пор, пока не будет готов отчёт (DONE).
 */
enum class CheckStatus {
    /** Задача создана, но анализ ещё не начался. */
    PENDING,

    /** Анализ выполняется. */
    RUNNING,

    /** Анализ завершён, отчёт готов. */
    DONE,

    /** Анализ упал (ошибка загрузки, клонирования и т.п.). */
    FAILED,
}